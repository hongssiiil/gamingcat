export function createForestOcclusion(){
    const ns='http://www.w3.org/2000/svg';
    const make=(tag,attrs)=>{const n=document.createElementNS(ns,tag);for(const [key,value] of Object.entries(attrs))n.setAttribute(key,value);return n;};
    const element=make('svg',{class:'road-forest-foreground',viewBox:'0 0 1023 769','aria-hidden':'true',focusable:'false'});
    const defs=make('defs',{}),clip=make('clipPath',{id:'road-foreground-clip',clipPathUnits:'userSpaceOnUse'});
    const shapes=occluders.map(({polygon})=>{
        const shape=make('polygon',{points:polygon.map(p=>p.join(',')).join(' ')});clip.append(shape);return shape;
    });
    defs.append(clip);element.append(defs,make('image',{href:'./images/backgrounds/road_white.png',width:1023,height:769,'clip-path':'url(#road-foreground-clip)'}));
    let previous=[];
    return {element,update(feetY){
        occluders.forEach(({depth},i)=>{
            const inFront=feetY<depth;
            if(previous[i]!==inFront){shapes[i].style.display=inFront?'':'none';previous[i]=inFront;}
        });
    }};
}

